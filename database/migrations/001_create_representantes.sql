CREATE TABLE representantes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    cnpj VARCHAR(18) NOT NULL UNIQUE,
    inscricao_estadual VARCHAR(14) DEFAULT NULL,
    nome_razao VARCHAR(150) NOT NULL,
    nome_fantasia VARCHAR(150) DEFAULT NULL,
    nome_exibicao VARCHAR(150) DEFAULT NULL,
    cnae VARCHAR(20) DEFAULT NULL,
    crt VARCHAR(10) DEFAULT NULL,
    data_fundacao DATE DEFAULT NULL,
    comissao_percentual DECIMAL(5,2) DEFAULT NULL,
    logradouro VARCHAR(100) DEFAULT NULL,
    numero VARCHAR(10) DEFAULT NULL,
    complemento VARCHAR(50) DEFAULT NULL,
    bairro VARCHAR(50) DEFAULT NULL,
    cep VARCHAR(10) DEFAULT NULL,
    estado CHAR(2) DEFAULT NULL,
    municipio VARCHAR(80) DEFAULT NULL,
    telefone VARCHAR(20) DEFAULT NULL,
    celular VARCHAR(20) DEFAULT NULL,
    email VARCHAR(100) DEFAULT NULL,
    observacoes TEXT DEFAULT NULL,
    ativo TINYINT(1) DEFAULT 1,
    senha VARCHAR(255) DEFAULT NULL,
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);